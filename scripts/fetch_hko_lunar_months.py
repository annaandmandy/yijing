"""
Builds the first day of every lunar month from lunar 1901 正月 to the last month that
starts in 2100, taken from the Hong Kong Observatory 公曆與農曆日期對照表 (one text file
per Gregorian year), and writes it twice:
- src/engine/hkoLunarMonths.js: the table PlumBlossomEngine.toLunarMoment looks dates up in.
- tests/fixtures/hko_lunar_months.json: one row per month, which the tests check the lookup against.

Source: https://www.hko.gov.hk/tc/gts/time/calendar/text/files/T{year}c.txt

Both files must come from HKO, never from our own code, and are never edited by hand.
Standard library only.

Usage: python3 scripts/fetch_hko_lunar_months.py
"""
import json
import os
import re
import time
import urllib.request

FIRST_YEAR = 1901
LAST_YEAR = 2100
URL = "https://www.hko.gov.hk/tc/gts/time/calendar/text/files/T{year}c.txt"
ROOT = os.path.join(os.path.dirname(__file__), "..")
OUT = os.path.join(ROOT, "tests", "fixtures", "hko_lunar_months.json")
TABLE = os.path.join(ROOT, "src", "engine", "hkoLunarMonths.js")

NUMERALS = {"正": 1, "一": 1, "二": 2, "三": 3, "四": 4, "五": 5, "六": 6,
            "七": 7, "八": 8, "九": 9, "十": 10, "十一": 11, "十二": 12, "冬": 11, "臘": 12}
# A row: 1901年2月19日   正月   星期二   [節氣]. Day rows have 初二/十五/廿九/三十 instead.
ROW = re.compile(r"^(\d{4})年(\d{1,2})月(\d{1,2})日\s+(\S+)")
MONTH = re.compile(r"^(閏)?(正|十二|十一|冬|臘|[一二三四五六七八九十])月$")


def fetch(year):
    for attempt in range(4):
        try:
            with urllib.request.urlopen(URL.format(year=year), timeout=30) as resp:
                return resp.read().decode("utf-8-sig")
        except OSError:
            if attempt == 3:
                raise
            time.sleep(2 * (attempt + 1))


def month_starts(year, text):
    """Yields (date, month, is_leap) for each lunar month that starts in this Gregorian year."""
    for line in text.splitlines():
        row = ROW.match(line.strip())
        if not row:
            continue
        y, m, d, lunar = row.groups()
        if int(y) != year:
            raise ValueError(f"T{year}c.txt has a row for {y}: {line!r}")
        month = MONTH.match(lunar)
        if month:
            yield f"{y}-{int(m):02d}-{int(d):02d}", NUMERALS[month.group(2)], month.group(1) is not None


def main():
    entries = []
    for year in range(FIRST_YEAR, LAST_YEAR + 1):
        found = list(month_starts(year, fetch(year)))
        if not 11 <= len(found) <= 14:
            raise ValueError(f"T{year}c.txt: {len(found)} month starts, expected 11-14")
        # Months before 正月 in a Gregorian year belong to the previous lunar year
        lunar_year = year - 1
        for date, month, is_leap in found:
            if month == 1 and not is_leap:
                lunar_year = year
            entries.append({"date": date, "lunarYear": lunar_year, "month": month, "isLeap": is_leap})
        print(f"{year}: {len(found)} month starts")

    # Lunar 1900's last months start in Jan 1901; the supported range begins at lunar 1901 正月.
    entries = [e for e in entries if e["lunarYear"] >= FIRST_YEAR]

    # Sanity: months run in order, each lunar year has 12 or 13 months starting with 正月.
    for prev, cur in zip(entries, entries[1:]):
        same_year = cur["lunarYear"] == prev["lunarYear"]
        ok = (same_year and (cur["month"] == prev["month"] + 1 and not cur["isLeap"] or
                             cur["month"] == prev["month"] and cur["isLeap"] and not prev["isLeap"])) or \
             (cur["lunarYear"] == prev["lunarYear"] + 1 and cur["month"] == 1 and not cur["isLeap"] and prev["month"] == 12)
        if not ok:
            raise ValueError(f"month sequence breaks between {prev} and {cur}")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump({
            "source": URL,
            "note": "Generated by scripts/fetch_hko_lunar_months.py. Do not edit by hand.",
            "months": entries,
        }, f, ensure_ascii=False, indent=0)
        f.write("\n")
    print(f"Wrote {len(entries)} month starts to {os.path.normpath(OUT)}")
    write_table(entries)


def write_table(entries):
    """One line per lunar year: its month starts as MM-DD, a trailing * marks the leap month (閏月)."""
    years = {}
    for e in entries:
        years.setdefault(e["lunarYear"], []).append(e)
    lines = []
    for year, months in years.items():
        cells = [e["date"][5:] + ("*" if e["isLeap"] else "") for e in months]
        lines.append(f'    "{year} {" ".join(cells)}"')
    with open(TABLE, "w", encoding="utf-8") as f:
        f.write(
            "// Generated by scripts/fetch_hko_lunar_months.py. Do not edit by hand; rerun the script.\n"
            f"// Source: Hong Kong Observatory 公曆與農曆日期對照表, {URL.format(year=FIRST_YEAR)}\n"
            f"//   … {URL.format(year=LAST_YEAR)} (one file per year).\n"
            "// One string per lunar year: \"<lunar year> <MM-DD of each month start>\", 正月 first.\n"
            "// Dates run on into the next Gregorian year when MM-DD goes backwards. A trailing * is the leap month (閏月).\n"
            "export const HKO_LUNAR_YEARS = [\n" + ",\n".join(lines) + "\n];\n"
            "\n// Dates the table covers: the first month start, to the last day of the last HKO table fetched.\n"
            f'export const HKO_RANGE = {{ first: "{entries[0]["date"]}", last: "{LAST_YEAR}-12-31" }};\n'
        )
    print(f"Wrote {len(years)} lunar years to {os.path.normpath(TABLE)}")


if __name__ == "__main__":
    main()
